# Using the Math Module for Calculations

num = int(input("Enter your Number: "))
import math

# Squareroot of the number
Sqr = math.sqrt(num)
print(f"Square root of {num}: {Sqr}.")

#Natural logarithm of the number
log = math.log(num)
print(f"logarithm of {num}: {log}.")

#Sine of the number
Sine = math.sin(num)
print(f"Sine of {num}: {Sine}.")